import assert from 'node:assert/strict';
import {mkdtempSync,symlinkSync,mkdirSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {conversationScope,ConversationWorkspace,scopedHistoryArgs,authorizeReply} from './conversation-scope.mjs';
const base=mkdtempSync(join(tmpdir(),'whale-scope-'));
const a=conversationScope('private','12345'),b=conversationScope('private','23456'),g=conversationScope('group','12345');
const wa=new ConversationWorkspace(base,a),wb=new ConversationWorkspace(base,b),wg=new ConversationWorkspace(base,g);
wa.write('diary/note.md','A_CANARY');wb.write('diary/note.md','B_CANARY');wg.write('diary/note.md','GROUP_CANARY');
assert.equal(wa.read('diary/note.md'),'A_CANARY');assert.equal(wb.read('diary/note.md'),'B_CANARY');assert.equal(wg.read('diary/note.md'),'GROUP_CANARY');
for(const bad of ['../private-23456/diary/note.md','C:/secret','/secret','x\\y','x:stream','nul.txt','a./b','a//b'])assert.throws(()=>wa.read(bad));
assert.throws(()=>wa.write('large','x'.repeat(65537)));
const outside=join(base,'outside');mkdirSync(outside);writeFileSync(join(outside,'secret'),'OUTSIDE_CANARY');
symlinkSync(outside,join(wa.root,'link'),'junction');assert.throws(()=>wa.read('link/secret'));assert.throws(()=>wa.write('link/secret','overwrite'));
assert.throws(()=>new ConversationWorkspace(join(wa.root,'link'),b));
assert.deepEqual(scopedHistoryArgs(a,{keyword:'hello'}),{keyword:'hello',conversation:'private:12345'});
assert.throws(()=>scopedHistoryArgs(a,{conversation:b.address}));assert.throws(()=>scopedHistoryArgs(a,{group_id:'12345'}));
assert.throws(()=>authorizeReply(a,{message_type:'private',user_id:'23456'}));
assert.deepEqual(authorizeReply(a,{message_type:'private',user_id:'12345'}),{kind:'private',id:12345});
assert.throws(()=>conversationScope('private','../12345'));
console.log('PASS workspace canaries, same numeric id different channel, traversal/ADS/device/junction rejection, bound history and reply scope; offline only');
