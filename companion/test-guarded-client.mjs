import assert from 'node:assert/strict';
import {SpendingBook,guardedClient} from './guarded-client.mjs';
const book=new SpendingBook(':memory:',10);
let calls=0;
const client=guardedClient(()=>({async respond(req,opts){calls++;assert.equal(req.max_output_tokens,4096);assert.equal(opts.diagnostic,true);return {attempts:[]};}}),book,{reservation:6});
await client.bind().respond({model:'deepseek-flash'});
await assert.rejects(()=>client.respond({model:'deepseek-flash'}),/allowance/);
assert.equal(calls,1);book.close();
const b=new SpendingBook(':memory:',10);
const id=b.reserve(6);b.settle(id,[{charges:[{quote:{currency:'CNY',basis:'marginal'},amount:0.000004,missing:[]}]}]);
b.reserve(6);
assert.throws(()=>b.reserve(1),/allowance/);b.close();
console.log(JSON.stringify({passed:true,scope:'Fake provider, reservation refusal before invocation, unknown usage remains reserved; no paid API calls'}));
const c=new SpendingBook(':memory:');
const peak=c.reserve(2_200_000);
c.settleDeepSeek(peak,[{meters:{input:1000,output:100},charges:[{quote:{currency:'USD'},amount:0}]}]);
assert.equal(c.db.prepare('SELECT actual FROM calls WHERE id=?').get(peak).actual,2800);
const unknown=c.reserve(2_200_000);
c.settleDeepSeek(unknown,[{meters:{input:null,output:0}}]);
assert.equal(c.db.prepare('SELECT state FROM calls WHERE id=?').get(unknown).state,'pending');
assert.throws(()=>c.settleDeepSeek(unknown,[{meters:{input:1,output:4097}}]),/bounds/);
assert.equal(c.db.prepare('SELECT state FROM calls WHERE id=?').get(unknown).state,'pending');
c.close();
console.log('PASS: CNY conservative ceiling independent of USD quotes; unknown and out-of-bound usage stay reserved');
const cachedBook=new SpendingBook(':memory:');
const cachedId=cachedBook.reserve(2_200_000);
cachedBook.settleDeepSeek(cachedId,[{meters:{input:1000,cachedInput:900,output:100}}]);
assert.equal(cachedBook.db.prepare('SELECT actual FROM calls WHERE id=?').get(cachedId).actual,1036);
cachedBook.close();console.log('PASS: measured cached input priced at peak cache rate, not uncached rate');
